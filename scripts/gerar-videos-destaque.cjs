// Rebuild the daily video catalog from the site's existing series.
// Usage: node scripts/gerar-videos-destaque.cjs
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const sources = [
  ["dadosPlaylistSolfejo.js", "Introdução ao solfejo", "IntroducaoSolfejo/index.html"],
  ["dadosVideoaulasPraticar.js", "Solfejos para Praticar", "VideoaulasSolfejosParaPraticar/index.html"],
  ["dadosSemanaMiMaior.js", "Semana em Mi Maior", "SemanaMiMaior/index.html"],
  ["dadosSemanaFaMaior.js", "Semana em Fá Maior", "SemanaFaMaior/index.html"],
  ["dadosSemanaSolMaior.js", "Semana em Sol Maior", "SemanaSolMaior/index.html"],
  ["dadosHarmonia.js", "Solfejo e harmonia", "IntroducaoHarmonia/index.html"],
  ["dadosVideoaulasMetronomo.js", "Estudando com o Metrônomo", "VideoaulasMetronomo/index.html"],
  ["dadosShortsPraticar.js", "Solfejos para Praticar · shorts", "ShortsSolfejosParaPraticar/index.html"],
  ["dadosShortsMetronomo.js", "Metrônomo · prática rítmica", "ShortsMetronomo/index.html"]
];
const seen = new Set();
const groups = sources.map(([file, category, series]) => {
  const source = fs.readFileSync(path.join(root, "jsnewmain", file), "utf8");
  const context = {};
  vm.runInNewContext(source.replace(/export\s*\{[^}]*\};?/g, "") + ";globalThis.rows=dados;", context);
  return context.rows.flatMap(row => {
    const variants = [["codigoVideo", ""]].concat(
      Object.keys(row).filter(key => /^bpm\d+$/.test(key)).map(key => [key, " · " + key.slice(3) + " BPM"])
    );
    return variants.flatMap(([key, suffix]) => {
      const id = row[key];
      if (!/^[A-Za-z0-9_-]{11}$/.test(id || "") || seen.has(id)) return [];
      seen.add(id);
      return [{
        id,
        title: (row.tituloVideo || row.tituloCabecalho || category).trim() + suffix,
        description: (row.resumoVideo || "").trim() || "Reserve um momento para ouvir, cantar e praticar com esta videoaula da série " + category + ".",
        category,
        series
      }];
    });
  });
});
// Interleave series to alternate subjects instead of showing entire series in sequence.
const videos = [];
for (let index = 0; index < Math.max(...groups.map(group => group.length)); index++) {
  for (const group of groups) if (group[index]) videos.push(group[index]);
}
// Store repeated series labels once and compact the records for delivery.
// Expand into the original object shape so the daily selection stays unchanged.
const series = sources.map(([, category, url]) => [category, url]);
const records = videos.map(video => [
  video.id, video.title, video.description,
  series.findIndex(([category, url]) => category === video.category && url === video.series)
]);
const output = "// Generated by scripts/gerar-videos-destaque.cjs. Edit the source series and rebuild.\n" +
  "(function(){var series=" + JSON.stringify(series) + ";window.videosDestaque=" +
  JSON.stringify(records) + ".map(function(row){return {id:row[0],title:row[1],description:row[2],category:series[row[3]][0],series:series[row[3]][1]};});}());\n";
fs.writeFileSync(path.join(root, "jsnewmain", "videos-destaque.js"), output, "utf8");
console.log(videos.length + " unique videos added to the daily catalog.");
